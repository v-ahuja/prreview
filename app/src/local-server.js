const securityHeaders = {
  'Cache-Control': 'no-store',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'no-referrer',
  'Content-Security-Policy': contentSecurityPolicy
};

export function defaultDataDir(env = process.env) {
  if (process.platform === 'win32') return join(env.APPDATA || join(homedir(), 'AppData', 'Roaming'), 'PR Walkthrough');
  if (process.platform === 'darwin') return join(homedir(), 'Library', 'Application Support', 'PR Walkthrough');
  return join(env.XDG_DATA_HOME || join(homedir(), '.local', 'share'), 'pr-walkthrough');
}

export function parsePrUrl(value) {
  let url;
  try { url = new URL(value); } catch { throw Object.assign(new Error('Enter a GitHub pull request URL.'), { status: 400 }); }
  const match = /^\/([A-Za-z0-9_.-]+)\/([A-Za-z0-9_.-]+)\/pull\/([1-9]\d*)\/?$/.exec(url.pathname);
  if (url.protocol !== 'https:' || url.hostname !== 'github.com' || url.port || url.username || url.password || !match)
    throw Object.assign(new Error('Enter a github.com pull request URL.'), { status: 400 });
  const [, owner, repo, rawNumber] = match;
  const number = Number(rawNumber);
  if (!Number.isSafeInteger(number)) throw Object.assign(new Error('Invalid PR number.'), { status: 400 });
  return { owner, repo, number, canonical: `https://github.com/${owner}/${repo}/pull/${number}` };
}

function selection(params) {
  const runner = params.get('runner') || 'codex';
  const model = (params.get('model') || '').trim();
  if (!runners.has(runner)) throw Object.assign(new Error('Choose Claude or Codex.'), { status: 400 });
  if (!/^[A-Za-z0-9._:/-]{0,100}$/.test(model)) throw Object.assign(new Error('Invalid model name.'), { status: 400 });
  return { runner, model };
}

async function readRuns(dataDir, pr) {
  const files = await readdir(dataDir).catch(error => { if (error.code === 'ENOENT') return []; throw error; });
  const runs = [];
  for (const file of files.filter(f => f.endsWith('.json') && !f.startsWith('.'))) {
    const run = JSON.parse(await readFile(join(dataDir, file), 'utf8'));
    if (run.pr === pr.canonical) runs.push(run);
  }
  return runs.sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}
async function saveRun(dataDir, run) {
  await mkdir(dataDir, { recursive: true, mode: 0o700 });
  const file = join(dataDir, `${run.id}.json`), temporary = `${file}.${randomUUID()}.tmp`;
  await writeFile(temporary, JSON.stringify(run), { mode: 0o600 });
  await rename(temporary, file);
}
async function reviewMark(dataDir, pr, sha) {
  const file = join(dataDir, `.review-${createHash('sha256').update(pr.canonical).digest('hex')}.json`);
  if (sha) {
    await mkdir(dataDir, { recursive: true, mode: 0o700 });
    await writeFile(file, JSON.stringify({ sha }), { mode: 0o600 });
    return sha;
  }
  return JSON.parse(await readFile(file, 'utf8').catch(error => { if (error.code === 'ENOENT') return '{}'; throw error; })).sha;
}

function page(title, body) { return layout(title, body, null, { local: true }); }

function send(res, status, body, type = 'text/html; charset=utf-8', headers = {}) {
  res.writeHead(status, { ...securityHeaders, 'Content-Type': type, ...headers });
  res.end(body);
}

function landing() {
  return page('Open a PR locally', `<section class="home"><div class="eyebrow">LOCAL PR WALKTHROUGHS</div><h1>Understand a PR, one slice at a time.</h1><p>Paste a GitHub pull request URL. The walkthrough is generated by your installed Claude or Codex CLI and saved on this computer.</p><form class="open-form" action="/"><input name="pr" type="url" required placeholder="https://github.com/owner/repo/pull/123" aria-label="GitHub PR URL"><button>Open PR</button></form></section>`);
}

function selectedUrl(pr, runner, model) {
  const params = new URLSearchParams({ pr: pr.canonical, runner });
  if (model) params.set('model', model);
  return `/?${params}`;
}

function selector(pr, runner, model) {
  return `<form class="local-selector" method="get" action="/"><input type="hidden" name="pr" value="${h(pr.canonical)}">${modelFields(generationPreferences({runner,model,modelCatalog:localModelCatalog}), {harnessLabel:'Runner',harnessName:'runner',harnesses:['codex','claude']})}<button class="secondary">Use runner</button></form>`;
}

function generateForm(pr, runner, model, csrf, label = 'Generate walkthrough') {
  return `<form method="post" action="/generate" class="local-generate"><input type="hidden" name="pr" value="${h(pr.canonical)}"><input type="hidden" name="runner" value="${h(runner)}"><input type="hidden" name="model" value="${h(model)}"><input type="hidden" name="csrf" value="${csrf}">${label === 'Upgrade walkthrough' ? '<input type="hidden" name="force" value="1">' : ''}<button>${h(label)}</button></form>`;
}

async function body(req) {
  const chunks = []; let size = 0;
  for await (const chunk of req) {
    size += chunk.length;
    if (size > 4096) throw Object.assign(new Error('Request is too large.'), { status: 413 });
    chunks.push(chunk);
  }
  return new URLSearchParams(Buffer.concat(chunks).toString('utf8'));
}

export function createLocalServer({ getToken = ghToken, fetchPull = getPull, generate = generateLocalWalkthrough,
  fetchCommits = listPullCommits, fetchCode = readCode, answer = answerQuestion, dataDir = defaultDataDir() } = {}) {
  const jobs = new Map(), chatBusy = new Set();
  const csrf = randomBytes(32).toString('base64url');
  const json = (res, status, data) => send(res, status, JSON.stringify(data), 'application/json; charset=utf-8');
  const server = http.createServer((req, res) => route(req, res).catch(error => {
    const status = [400, 403, 404, 409, 413, 422, 429].includes(error.status) ? error.status : 500;
    if (status === 500) console.error('Local walkthrough error:', error);
    if (/^\/(chat|code|reviewed)/.test(req.url)) return json(res, status, { error: error.message });
    send(res, status, page('Unable to open walkthrough', `<section class="panel"><h1>Unable to open walkthrough</h1><p>${h(error.message)}</p></section>`));
  }));
  const fail = (message, status = 400) => { throw Object.assign(new Error(message), { status }); };
  async function route(req, res) {
    const origin = `http://127.0.0.1:${server.address().port}`;
    if (req.headers.host !== `127.0.0.1:${server.address().port}`) return send(res, 403, 'Forbidden');
    const url = new URL(req.url, origin);
    if (await serveAsset(req, res, url.pathname)) return;
    if (req.method === 'GET' && url.pathname === '/') {
      const input = url.searchParams.get('pr');
      if (!input) return send(res, 200, landing());
      const pr = parsePrUrl(input), { runner, model } = selection(url.searchParams);
      const pull = await fetchPull(await getToken(), pr.owner, pr.repo, pr.number);
      const runs = await readRuns(dataDir, pr);
      const version = url.searchParams.get('version');
      let saved = version ? runs.find(r => r.id === version) : runs.find(r => r.baseSha === pull.base.sha && r.headSha === pull.head.sha && (r.scope || 'full') === 'full' && r.runner === runner && r.model === model);
      if (version && !saved) fail('Review version not found.', 404);
      const key = [pr.canonical, pull.base.sha, pull.head.sha, runner, model].join(':');
      const job = jobs.get(url.searchParams.get('job') || key);
      if (job?.id) saved = runs.find(r => r.id === job.id) || saved;
      const mark = await reviewMark(dataDir, pr);
      const stale = saved && (saved.baseSha !== pull.base.sha || saved.headSha !== pull.head.sha);
      const history = `<details class="versions"><summary>Review history (${runs.length})</summary><div class="history-menu"><a href="${h(selectedUrl(pr, runner, model))}">Current PR</a>${runs.map(r => `<a href="${h(selectedUrl(pr, r.runner, r.model))}&amp;version=${h(r.id)}"><strong>${h(scopeLabel(r))}</strong><span>${h(r.headSha.slice(0,7))} · ${h(r.createdAt.slice(0,10))}${r.headSha !== pull.head.sha ? ' · Archived' : ''}</span></a>`).join('')}</div></details>`;
      const intro = `<div class="breadcrumb"><a href="/">Home</a> / ${h(pr.owner)}/${h(pr.repo)} / PR #${pr.number}</div><div class="hero"><div><div class="eyebrow">LOCAL PR WALKTHROUGH</div><h1>${h(pull.title)}</h1><p><a href="${h(pr.canonical)}">${h(pr.owner)}/${h(pr.repo)}#${pr.number} ↗</a> · ${h(pull.head.sha.slice(0, 8))}</p></div>${history}</div><details class="local-options"><summary>Runner & review scope</summary>${selector(pr, runner, model)}<form method="post" action="/generate" class="scope-form"><input type="hidden" name="pr" value="${h(pr.canonical)}"><input type="hidden" name="runner" value="${h(runner)}"><input type="hidden" name="model" value="${h(model)}"><input type="hidden" name="csrf" value="${csrf}"><label>Review scope<select name="scope"><option value="full">Entire pull request</option><option value="since"${mark ? '' : ' disabled'}>Since my last completed review</option><option value="range">Selected commits</option></select></label><div class="commit-range" hidden><label>First commit SHA (inclusive)<input name="from" pattern="[0-9a-f]{40}" placeholder="Full commit SHA from GitHub"></label><label>Last commit SHA (inclusive)<input name="to" pattern="[0-9a-f]{40}" placeholder="Full commit SHA from GitHub"></label></div><button>Generate walkthrough</button></form></details>`;
      let content;
      if (job?.status === 'running') content = `<section class="panel empty"><h2>Building the walkthrough</h2><p>${h(runner)} is reading the pinned PR diff. This page will update automatically.</p></section>`;
      else if (job?.status === 'failed') content = `<section class="panel empty"><h2>Generation failed</h2><p>${h(job.error)}</p></section>${generateForm(pr, runner, model, csrf, 'Retry walkthrough')}`;
      else if (saved) content = `${stale ? '<div class="notice">Archived review — pinned to an earlier PR version.</div>' : ''}<div class="review-version-bar"><strong>${h(scopeLabel(saved))}</strong><span>All slices pre-generated · ${h(saved.headSha.slice(0,7))}</span></div>${renderWalkthrough(saved.result, `local:${saved.id}`, { apiBase: '', query: new URLSearchParams({ pr: pr.canonical, version: saved.id }).toString(), csrf, scope: saved.scope || 'full', generationPreferences:generationPreferences({runner:saved.runner,model:saved.model,modelCatalog:localModelCatalog}) })}${!saved.result.evidence ? generateForm(pr, runner, model, csrf, 'Upgrade walkthrough') : ''}`;
      else content = `<section class="panel"><h2>Ready to generate</h2><p>The diff is fetched using your GitHub login. The selected CLI prepares every slice before you begin.</p>${generateForm(pr, runner, model, csrf)}</section>`;
      return send(res, 200, page(`#${pr.number} ${pull.title}`, intro + content), 'text/html; charset=utf-8', job?.status === 'running' ? { Refresh: '3' } : {});
    }
    if (req.method === 'POST' && url.pathname === '/generate') {
      const form = await body(req);
      if (form.get('csrf') !== csrf) return send(res, 403, 'Session expired. Reload and try again.');
      const pr = parsePrUrl(form.get('pr')), { runner, model } = selection(form);
      const token = await getToken(), pull = await fetchPull(token, pr.owner, pr.repo, pr.number);
      const commits = form.get('scope') === 'range' ? await fetchCommits(token, pr.owner, pr.repo, pr.number) : [];
      const scope = resolveScope(form, pull, commits, await reviewMark(dataDir, pr));
      const key = [pr.canonical, pull.base.sha, pull.head.sha, runner, model, ...(scope.scope === 'full' ? [] : [scope.scope, scope.startSha, scope.endSha])].join(':');
      const existing = (await readRuns(dataDir, pr)).find(r => r.baseSha === pull.base.sha && r.headSha === pull.head.sha && r.runner === runner && r.model === model && (r.scope || 'full') === scope.scope && (r.startSha || '') === scope.startSha && (r.endSha || '') === scope.endSha);
      if (existing && form.get('force') !== '1') return send(res, 303, '', 'text/html; charset=utf-8', { Location: selectedUrl(pr, runner, model) + '&version=' + existing.id });
      if (jobs.get(key)?.status !== 'running') {
        const job = { status: 'running' }; jobs.set(key, job);
        Promise.resolve().then(() => generate({ owner: pr.owner, repo: pr.repo, number: pr.number, title: pull.title,
          baseSha: scope.startSha || pull.base.sha, headSha: scope.endSha || pull.head.sha, scope: scope.scope, token, runner, model }))
          .then(async result => { const id = randomUUID(); await saveRun(dataDir, { id, createdAt: new Date().toISOString(), pr: pr.canonical, title: pull.title,
            baseSha: pull.base.sha, headSha: pull.head.sha, runner, model, ...scope, result }); job.status = 'ready'; job.id = id; })
          .catch(error => { console.error('Local generation failed:', error); job.status = 'failed'; job.error = error.message; });
      }
      return send(res, 303, '', 'text/html; charset=utf-8', { Location: selectedUrl(pr, runner, model) + '&job=' + encodeURIComponent(key) });
    }
    if (['/code','/chat','/reviewed'].includes(url.pathname)) {
      const pr = parsePrUrl(url.searchParams.get('pr'));
      const token = await getToken(), pull = await fetchPull(token, pr.owner, pr.repo, pr.number);
      const saved = (await readRuns(dataDir, pr)).find(r => r.id === url.searchParams.get('version'));
      if (!saved) fail('Review version not found.', 404);
      if (req.method === 'GET' && url.pathname === '/code') {
        const evidence = saved.result.evidence, file = url.searchParams.get('file');
        if (!evidence) fail('Regenerate this older walkthrough to enable the full editor.', 409);
        if (!evidence.files.includes(file)) fail('File not in this walkthrough.', 404);
        const side = url.searchParams.get('side') === 'base' ? 'base' : 'head';
        const sourceFile = evidence.sourceFiles ? evidence.sourceFiles[file]?.[side] : file;
        if (!sourceFile) fail(`This file does not exist in the ${side} version. Choose the other version.`, 404);
        return json(res, 200, await fetchCode(token, pr.owner, pr.repo, side === 'base' ? evidence.baseSha : evidence.headSha, sourceFile));
      }
      if (req.method !== 'POST') fail('Not found', 404);
      const chunks = []; let size = 0;
      for await (const chunk of req) { size += chunk.length; if (size > 3_000_000) fail('Request too large', 413); chunks.push(chunk); }
      const input = JSON.parse(Buffer.concat(chunks).toString('utf8'));
      if (input.csrf !== csrf) fail('Session expired. Reload and try again.', 403);
      if (url.pathname === '/reviewed') {
        if ((saved.scope || 'full') === 'full' && saved.headSha === pull.head.sha && saved.baseSha === pull.base.sha) await reviewMark(dataDir, pr, saved.headSha);
        return json(res, 200, { message: 'Walkthrough complete. Current full-PR reviews are saved as the baseline for your next review.' });
      }
      if (chatBusy.has(saved.id)) fail('Wait for your current answer to finish.', 429);
      const choice=modelSelection(input,{runner:saved.runner,model:saved.model});
      chatBusy.add(saved.id);
      try { return json(res, 200, await answer({ result: saved.result, input, runner: choice.runner, model: choice.model })); }
      finally { chatBusy.delete(saved.id); }
    }
    return send(res, 404, page('Not found', '<section class="panel"><h1>Not found</h1></section>'));
  }
  return server;
}
